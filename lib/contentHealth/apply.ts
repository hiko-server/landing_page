/**
 * Applies content health fixes (SERVER-ONLY) — each through the save path an
 * editor save takes, so a fix is an ordinary, undoable edit:
 *
 *   posts / case studies  compile check (422 rules) → poster import →
 *                         version check → writeOne (version snapshot for the
 *                         history drawer, SQLite + R2 mirror) → the pages
 *                         /api/admin/posts|work regenerate
 *   /now /uses /about     the same with writePage, regenerating the page
 *   CV                    registry validation → snapshot → writeCvData with an
 *                         atomic version precondition → CV pages + PDFs
 *   home                  normalizeHomeWrite → logo metrics → snapshot →
 *                         writeHome with the precondition → home pages + PDFs
 *
 * The compiled-MDX memo is keyed on the body and the upload variant state
 * (lib/mdx compileMdxCached), so a changed body or new variants compile
 * fresh by construction.
 *
 * The report is recomputed first and each requested id looked up in it — the
 * client only names issues, it never sends content. Optimistic concurrency:
 * every request carries the item version its report showed; an item that
 * changed since answers VERSION_CONFLICT for its fixes and nothing of it is
 * written. Several fixes for one item are applied together in one save.
 * An issue that is no longer in the report counts as done (GONE).
 *
 * Remote images are downloaded once per request through lib/remoteImage and
 * stored with the upload pipeline (lib/imageVariants storeUpload), at most
 * MAX_IMPORTS per request within IMPORT_BUDGET_MS; the rest is DEFERRED
 * (the panel calls again). Responsive sizes are generated by the
 * media-optimize pipeline, passed in as `generateVariants`.
 */

export const MAX_FIXES_PER_REQUEST = 100
export const MAX_IMPORTS = 6
export const IMPORT_BUDGET_MS = 60_000

export type VariantRun = {
  /** Uploads that now have all their variants. */
  done: ReadonlySet<string>
  errors: Array<{ name: string; error: string }>
  busy: boolean
  /** Public pages to regenerate (they embed the new srcsets). */
  paths: string[]
}

export type ApplyDeps = {
  log: Logger
  generateVariants: (names: ReadonlySet<string>) => Promise<VariantRun>
  /** Download + store a remote image; returns the upload URL (default: lib/remoteImage + storeUpload). */
  importImage?: (url: string) => Promise<string>
  now?: () => number
}

async function defaultImport(url: string): Promise<string> {
  const remote = await fetchRemoteImage(url)
  const stored = await storeUpload(remote.buf, remote.mime, remote.name)
  return stored.url
}

function importError(err: unknown): string {
  if (err instanceof RemoteImageError || err instanceof ImageRejectedError) return err.message
  return err instanceof Error ? err.message : String(err)
}

// ── Pure helpers ──────────────────────────────────────────────────────────

function getAt(root: unknown, path: ReadonlyArray<string | number>): unknown {
  let cur: any = root
  for (const seg of path) {
    if (cur == null) return undefined
    cur = cur[seg as any]
  }
  return cur
}

function setAt(root: unknown, path: ReadonlyArray<string | number>, value: unknown): void {
  let cur: any = root
  for (const seg of path.slice(0, -1)) cur = cur?.[seg as any]
  if (cur && typeof cur === 'object') cur[path[path.length - 1] as any] = value
}

const clone = <T>(v: T): T => JSON.parse(JSON.stringify(v)) as T

function fragmentOf(raw: string): string {
  const i = raw.indexOf('#')
  return i === -1 ? '' : raw.slice(i)
}

/** The new spelling of a stored or written URL for one fix; null when the fix does not apply to it. */
function rewriteValue(
  spec: ApplySpec,
  raw: string,
  imported: ReadonlyMap<string, string>
): string | null {
  switch (spec.op) {
    case 'strip-tracking':
      return stripTrackingParams(raw)
    case 'use-new-url':
      if (!/^https?:\/\//i.test(raw) || linkKey(raw) !== spec.key) return null
      return fragmentOf(spec.to) ? spec.to : `${spec.to}${fragmentOf(raw)}`
    case 'import-image':
      return imported.get(spec.url) ?? null
    default:
      return null
  }
}

/** Does this URL (as parsed from the body) belong to the fix? */
function matches(spec: ApplySpec, url: string): boolean {
  if (spec.op === 'strip-tracking' || spec.op === 'use-new-url') return linkKey(url) === spec.key
  if (spec.op === 'import-image') return url === spec.url
  return false
}

/**
 * Apply one fix to a body + document in memory. Returns false when there was
 * nothing left to change (the problem is gone).
 */
export function applyToContent(
  spec: ApplySpec,
  state: { body: string; doc: Record<string, any> },
  imported: ReadonlyMap<string, string> = new Map()
): boolean {
  if (spec.op === 'generate-variants') return false
  if (spec.op === 'breaks') {
    const r = fixBreaks(state.body, new Set([spec.fix]))
    state.body = r.body
    return r.changed > 0
  }
  const place: Place = spec.place
  if (place.at === 'body') {
    const r = rewriteUrls(state.body, (url) =>
      matches(spec, url) ? (raw) => rewriteValue(spec, raw, imported) ?? raw : null
    )
    state.body = r.body
    return r.changed > 0
  }
  const current = getAt(state.doc, place.path)
  if (current !== place.value || typeof current !== 'string') return false
  const next = rewriteValue(spec, current, imported)
  if (next === null || next === current) return false
  setAt(state.doc, place.path, next)
  return true
}

// ── The request ───────────────────────────────────────────────────────────

type Work = { req: FixRequest; issue: InternalIssue; spec: ApplySpec }

function conflictMessage(item: HealthItem | undefined): string {
  return `${item ? `“${item.title}”` : 'This item'} was changed since the report was loaded. Refresh the report and try again.`
}

export async function applyFixes(
  res: NextApiResponse,
  requests: readonly FixRequest[],
  deps: ApplyDeps
): Promise<FixResponse> {
  const analysis = buildAnalysis(deps.now ? deps.now() : Date.now())
  const byId = new Map(analysis.issues.map((i) => [i.id, i]))
  const results = new Map<string, FixResult>()
  const set = (id: string, r: Omit<FixResult, 'id'>) => results.set(id, { id, ...r })
  const work: Work[] = []

  for (const req of requests.slice(0, MAX_FIXES_PER_REQUEST)) {
    if (results.has(req.id) || work.some((w) => w.req.id === req.id)) continue
    const issue = byId.get(req.id)
    if (!issue) {
      set(req.id, { ok: true, code: 'GONE' })
      continue
    }
    if (!issue.apply) {
      set(req.id, {
        ok: false,
        code: 'NO_FIX',
        error: 'This issue has no automatic fix; open it in the editor.',
      })
      continue
    }
    const spec = issue.apply
    if (
      spec.op !== 'generate-variants' &&
      typeof req.version === 'number' &&
      analysis.items[issue.item]?.version !== req.version
    ) {
      set(req.id, {
        ok: false,
        code: 'VERSION_CONFLICT',
        error: conflictMessage(analysis.items[issue.item]),
      })
      continue
    }
    work.push({ req, issue, spec })
  }

  // Remote images: download each once.
  const imported = new Map<string, string>()
  const importUrls = Array.from(
    new Set(work.flatMap((w) => (w.spec.op === 'import-image' ? [w.spec.url] : [])))
  )
  const importFailed = new Map<string, { code: 'FAILED' | 'DEFERRED'; error: string }>()
  const started = Date.now()
  for (const [n, url] of importUrls.entries()) {
    if (n >= MAX_IMPORTS || Date.now() - started > IMPORT_BUDGET_MS) {
      importFailed.set(url, {
        code: 'DEFERRED',
        error: 'Not imported yet — apply again to continue.',
      })
      continue
    }
    try {
      imported.set(url, await (deps.importImage ?? defaultImport)(url))
    } catch (err) {
      importFailed.set(url, {
        code: 'FAILED',
        error: `Could not import the image: ${importError(err)}`,
      })
    }
  }

  // Responsive sizes.
  const paths: string[] = []
  const confirm: string[] = []
  const uploads = new Set(
    work.flatMap((w) => (w.spec.op === 'generate-variants' ? [w.spec.upload] : []))
  )
  if (uploads.size) {
    let run: VariantRun
    try {
      run = await deps.generateVariants(uploads)
    } catch (err) {
      run = { done: new Set(), errors: [], busy: false, paths: [] }
      deps.log.warn('generating variants failed', { err })
    }
    paths.push(...run.paths)
    for (const w of work) {
      if (w.spec.op !== 'generate-variants') continue
      const name = w.spec.upload
      if (run.done.has(name)) set(w.req.id, { ok: true })
      else if (run.busy)
        set(w.req.id, {
          ok: false,
          code: 'FAILED',
          error: 'Another optimisation run is in progress; try again in a minute.',
        })
      else
        set(w.req.id, {
          ok: false,
          code: 'FAILED',
          error:
            run.errors.find((e) => e.name === name)?.error || 'The sizes could not be generated.',
        })
    }
  }

  // Content edits, one save per item.
  const groups = new Map<string, Work[]>()
  for (const w of work) {
    if (w.spec.op === 'generate-variants') continue
    if (w.spec.op === 'import-image' && importFailed.has(w.spec.url)) {
      const f = importFailed.get(w.spec.url) as { code: 'FAILED' | 'DEFERRED'; error: string }
      set(w.req.id, { ok: false, code: f.code, error: f.error })
      continue
    }
    groups.set(w.issue.item, [...(groups.get(w.issue.item) || []), w])
  }

  for (const [key, list] of groups) {
    const item = analysis.items[key]
    const fail = (code: FixResult['code'], error: string) =>
      list.forEach((w) => set(w.req.id, { ok: false, code, error }))
    try {
      if (item?.kind === 'post' || item?.kind === 'work' || item?.kind === 'page') {
        const out = await saveDoc(item, list, imported, deps)
        if (!out.ok) {
          fail(out.code, out.error)
          continue
        }
        list.forEach((w) =>
          set(w.req.id, out.changed.has(w.req.id) ? { ok: true } : { ok: true, code: 'GONE' })
        )
        paths.push(...out.paths)
      } else if (item?.kind === 'cv' || item?.kind === 'home') {
        const out =
          item.kind === 'cv'
            ? await saveCv(item, list, imported, deps)
            : await saveHome(item, list, imported, deps)
        if (!out.ok) {
          fail(out.code, out.error)
          continue
        }
        list.forEach((w) =>
          set(w.req.id, out.changed.has(w.req.id) ? { ok: true } : { ok: true, code: 'GONE' })
        )
        paths.push(...out.paths)
        confirm.push(...out.paths)
      } else {
        fail('GONE', 'The item no longer exists.')
      }
    } catch (err) {
      deps.log.error('content health fix failed', { item: key, err })
      fail('FAILED', 'The fix could not be saved.')
    }
  }

  const unique = Array.from(new Set(paths))
  const failed = unique.length
    ? await revalidatePaths(res, unique, { confirm: Array.from(new Set(confirm)) })
    : []
  const ordered = requests
    .slice(0, MAX_FIXES_PER_REQUEST)
    .map((r) => results.get(r.id))
    .filter((r): r is FixResult => !!r)
  const deduped = ordered.filter((r, i) => ordered.findIndex((o) => o.id === r.id) === i)
  return {
    results: deduped,
    applied: deduped.filter((r) => r.ok && r.code !== 'GONE').length,
    revalidated: unique.filter((p) => !failed.includes(p)),
    ...(failed.length ? { revalidateFailed: failed } : {}),
  }
}

type SaveOutcome =
  | { ok: true; changed: Set<string>; paths: string[] }
  | { ok: false; code: FixResult['code']; error: string }

async function saveDoc(
  item: HealthItem,
  list: Work[],
  imported: ReadonlyMap<string, string>,
  deps: ApplyDeps
): Promise<SaveOutcome> {
  const slash = item.key.indexOf('/')
  const name = item.key.slice(slash + 1)
  const page: PageName | null = item.kind === 'page' && isPageName(name) ? name : null
  const collection: Collection | null =
    item.kind === 'post' ? 'blog' : item.kind === 'work' ? 'work' : null
  const read = () => (page ? readPage(page) : collection ? readOne(collection, name) : null)
  const current = read()
  if (!current || current.updatedAt === 0)
    return { ok: false, code: 'GONE', error: 'The item no longer exists.' }
  if (current.updatedAt !== item.version)
    return { ok: false, code: 'VERSION_CONFLICT', error: conflictMessage(item) }

  const state = { body: current.body, doc: clone(current.frontmatter || {}) as Record<string, any> }
  const changed = new Set<string>()
  for (const w of list) if (applyToContent(w.spec, state, imported)) changed.add(w.req.id)
  if (!changed.size) return { ok: true, changed, paths: [] }

  if (state.body.trim()) {
    const problem = await mdxProblem(state.body)
    if (problem)
      return {
        ok: false,
        code: 'FAILED',
        error: `The fix would leave the body invalid (${problem.error}); nothing was saved.`,
      }
    await ensurePosters(state.body)
  }
  // Version check and write run without an await in between (single Node process).
  if (read()?.updatedAt !== item.version)
    return { ok: false, code: 'VERSION_CONFLICT', error: conflictMessage(item) }
  const result = page
    ? await writePage(page, state.doc, state.body)
    : await writeOne(collection as Collection, name, state.doc, state.body)
  if (!result.ok) return { ok: false, code: 'FAILED', error: result.error }
  if ('r2Warning' in result)
    deps.log.warn('content health fix saved without the R2 copy', {
      item: item.key,
      warning: result.r2Warning,
    })
  const paths = page
    ? [`/${page}`]
    : [
        ...collectionPaths(
          collection as Collection,
          name,
          listAll(collection as Collection).map((i) => i.slug)
        ),
        ...COLLECTION_EXTRA_PATHS[collection as Collection],
        ...CV_DOCUMENT_PATHS,
      ]
  return { ok: true, changed, paths }
}

async function saveCv(
  item: HealthItem,
  list: Work[],
  imported: ReadonlyMap<string, string>,
  deps: ApplyDeps
): Promise<SaveOutcome> {
  const current = readCvDataWithVersion()
  if (current.version !== item.version)
    return { ok: false, code: 'VERSION_CONFLICT', error: conflictMessage(item) }
  const doc = clone({ en: current.en, zh: current.zh }) as Record<string, any>
  const state = { body: '', doc }
  const changed = new Set<string>()
  for (const w of list) if (applyToContent(w.spec, state, imported)) changed.add(w.req.id)
  if (!changed.size) return { ok: true, changed, paths: [] }
  const touched = (lang: 'en' | 'zh') =>
    stableStringify(doc[lang]) !== stableStringify(current[lang])
  const checked = validateCvDoc({
    en: touched('en') ? doc.en : undefined,
    zh: touched('zh') ? doc.zh : undefined,
  })
  if (!checked.ok)
    return {
      ok: false,
      code: 'FAILED',
      error: `The CV would not pass its checks (${checked.errors[0]?.message || 'invalid value'}); nothing was saved.`,
    }
  const nav = trackPublicationsNav()
  try {
    saveCvSnapshot()
  } catch (err) {
    deps.log.warn('CV snapshot failed', { before: 'content health fix', err })
  }
  const written = await writeCvData(
    { en: doc.en, zh: doc.zh },
    { precondition: (v) => v === item.version }
  )
  if (!written.ok)
    return written.conflict
      ? { ok: false, code: 'VERSION_CONFLICT', error: conflictMessage(item) }
      : { ok: false, code: 'FAILED', error: written.error }
  if (written.r2Warning)
    deps.log.warn('content health fix saved without the R2 copy', {
      item: 'cv',
      warning: written.r2Warning,
    })
  warmCvExports()
  return {
    ok: true,
    changed,
    paths: Array.from(new Set([...CV_PAGE_PATHS, ...nav.pathsIfChanged()])),
  }
}

async function saveHome(
  item: HealthItem,
  list: Work[],
  imported: ReadonlyMap<string, string>,
  deps: ApplyDeps
): Promise<SaveOutcome> {
  const current = readHomeWithVersion()
  if (!current.home)
    return { ok: false, code: 'GONE', error: 'The home document no longer exists.' }
  if (current.version !== item.version)
    return { ok: false, code: 'VERSION_CONFLICT', error: conflictMessage(item) }
  const doc = clone(current.home) as unknown as Record<string, any>
  const state = { body: '', doc }
  const changed = new Set<string>()
  for (const w of list) if (applyToContent(w.spec, state, imported)) changed.add(w.req.id)
  if (!changed.size) return { ok: true, changed, paths: [] }
  const checked = normalizeHomeWrite(doc as unknown as HomeData)
  if (!checked.ok)
    return {
      ok: false,
      code: 'FAILED',
      error: `The home page would not pass its checks (${checked.errors[0]?.message || 'invalid value'}); nothing was saved.`,
    }
  const next: HomeData = {
    ...checked.home,
    brands: await withLogoMetrics(checked.home.brands, current.home.brands, deps.log),
  }
  try {
    saveHomeSnapshot()
  } catch (err) {
    deps.log.warn('home snapshot failed', { before: 'content health fix', err })
  }
  const written = await writeHome(next, { precondition: (v) => v === item.version })
  if (!written.ok)
    return written.conflict
      ? { ok: false, code: 'VERSION_CONFLICT', error: conflictMessage(item) }
      : { ok: false, code: 'FAILED', error: written.error }
  if (written.r2Warning)
    deps.log.warn('content health fix saved without the R2 copy', {
      item: 'home',
      warning: written.r2Warning,
    })
  warmCvExports()
  return { ok: true, changed, paths: [...HOME_PAGE_PATHS] }
}
